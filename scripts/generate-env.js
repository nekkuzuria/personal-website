#!/usr/bin/env node
/*
 * Generates env.js from environment variables.
 *
 * Local:  node scripts/generate-env.js   (reads .env automatically)
 * Vercel: runs as the build command with the project's Environment Variables.
 *
 * env.js is browser-readable by design. Only put public values here
 * (SUPABASE_URL, the anon key, ADMIN_EMAIL) — never a service_role key.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const keys = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'ADMIN_EMAIL'];

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const fileEnv = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : {};
const env = { ...fileEnv, ...process.env };

const values = {};
for (const key of keys) values[key] = env[key] || '';

const missing = keys.filter(key => !values[key]);
if (missing.length) {
  console.warn(`[env] Missing ${missing.join(', ')}. The site will show demo content until these are set.`);
  if (process.env.VERCEL) {
    console.error('[env] Refusing to build on Vercel without all required variables.');
    process.exit(1);
  }
}

const output = `/* Generated by scripts/generate-env.js. Do not edit or commit this file. */
window.ENV = ${JSON.stringify(values, null, 2)};
`;

fs.writeFileSync(path.join(root, 'env.js'), output);
console.log('[env] Wrote env.js');
